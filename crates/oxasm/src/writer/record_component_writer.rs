//! ASM's `RecordComponentWriter`: [`RecordComponentWriterState`] holds what ASM's writer holds,
//! and [`RecordComponentWriter`], the visitor a class writer returns, borrows it with the symbol
//! table.

use crate::attribute::Attribute;
use crate::jstr::JavaStr;
use crate::type_path::TypePath;
use crate::type_reference::TypeReference;
use crate::visitor::{AnnotationVisitor, RecordComponentVisitor};
use crate::writer::annotation_writer::{
    MemberAnnotations, compute_member_annotations_size, put_member_annotations,
};
use crate::writer::attributes::{
    AttributeList, AttributePrototypes, compute_standard_attributes_size, put_standard_attributes,
};
use crate::writer::byte_vector::ByteVector;
use crate::writer::symbol_table::SymbolTable;

/// A `record_component_info` structure being written (ASM's `RecordComponentWriter` fields).
#[derive(Debug)]
pub(crate) struct RecordComponentWriterState {
    // Note: fields are ordered as in the record_component_info structure, and those related to
    // attributes are ordered as in Section 4.7 of the JVMS.
    /// The `name_index` field of the Record attribute.
    name_index: i32,
    /// The `descriptor_index` field of the Record attribute.
    descriptor_index: i32,
    /// The `signature_index` field of the Signature attribute of this record component, or 0
    /// if there is no Signature attribute.
    signature_index: i32,
    /// The runtime (in)visible (type) annotations of this record component.
    annotations: MemberAnnotations,
    /// The non standard attributes of this record component.
    attributes: AttributeList,
}

impl RecordComponentWriterState {
    /// Constructs a new record component writer state (ASM's `RecordComponentWriter`
    /// constructor).
    pub(crate) fn new(
        symbol_table: &mut SymbolTable,
        name: &JavaStr,
        descriptor: &JavaStr,
        signature: Option<&JavaStr>,
    ) -> RecordComponentWriterState {
        let name_index = symbol_table.add_constant_utf8(name);
        let descriptor_index = symbol_table.add_constant_utf8(descriptor);
        let signature_index = signature.map_or(0, |s| symbol_table.add_constant_utf8(s));
        RecordComponentWriterState {
            name_index,
            descriptor_index,
            signature_index,
            annotations: MemberAnnotations::default(),
            attributes: AttributeList::default(),
        }
    }

    /// Returns the size of the record component JVMS structure generated by this writer, and
    /// adds the names of its attributes to the constant pool.
    pub(crate) fn compute_record_component_info_size(
        &mut self,
        symbol_table: &mut SymbolTable,
    ) -> usize {
        // name_index, descriptor_index and attributes_count fields use 6 bytes.
        let mut size = 6;
        size += compute_standard_attributes_size(symbol_table, 0, self.signature_index);
        size += compute_member_annotations_size(symbol_table, &self.annotations);
        if !self.attributes.is_empty() {
            size += self.attributes.compute_attributes_size(symbol_table, None);
        }
        size
    }

    /// Puts the content of the `record_component_info` JVMS structure generated by this writer
    /// into the given byte vector.
    #[allow(clippy::cast_possible_truncation, clippy::cast_possible_wrap)] // Java's ints
    pub(crate) fn put_record_component_info(
        &mut self,
        symbol_table: &mut SymbolTable,
        output: &mut ByteVector,
    ) {
        output
            .put_short(self.name_index)
            .put_short(self.descriptor_index);
        // Compute and put the attributes_count field.
        // For ease of reference, we use here the same attribute order as in Section 4.7 of the
        // JVMS.
        let mut attributes_count = 0;
        if self.signature_index != 0 {
            attributes_count += 1;
        }
        attributes_count += self.annotations.attribute_count();
        attributes_count += self.attributes.len();
        output.put_short(attributes_count as i32);
        put_standard_attributes(symbol_table, 0, self.signature_index, output);
        put_member_annotations(symbol_table, &self.annotations, output);
        if !self.attributes.is_empty() {
            self.attributes.put_attributes(symbol_table, None, output);
        }
    }

    /// Collects the attributes of this record component into the given set of attribute
    /// prototypes.
    pub(crate) fn collect_attribute_prototypes(&self, prototypes: &mut AttributePrototypes) {
        self.attributes.collect_attribute_prototypes(prototypes);
    }
}

/// A [`RecordComponentVisitor`] that generates a corresponding `record_component_info`
/// structure.
pub(crate) struct RecordComponentWriter<'a> {
    pub(crate) symbol_table: &'a mut SymbolTable,
    pub(crate) state: &'a mut RecordComponentWriterState,
}

impl RecordComponentVisitor for RecordComponentWriter<'_> {
    fn visit_annotation<'b>(
        &'b mut self,
        descriptor: &JavaStr,
        visible: bool,
    ) -> Option<Box<dyn AnnotationVisitor + 'b>> {
        self.state
            .annotations
            .visit_annotation(self.symbol_table, descriptor, visible)
    }

    fn visit_type_annotation<'b>(
        &'b mut self,
        type_ref: TypeReference,
        type_path: Option<&TypePath>,
        descriptor: &JavaStr,
        visible: bool,
    ) -> Option<Box<dyn AnnotationVisitor + 'b>> {
        self.state.annotations.visit_type_annotation(
            self.symbol_table,
            type_ref,
            type_path,
            descriptor,
            visible,
        )
    }

    fn visit_attribute(&mut self, attribute: &Attribute) {
        // Store the attributes in the <i>reverse</i> order of their visit by this method.
        self.state.attributes.push(attribute);
    }

    fn visit_end(&mut self) {
        // Nothing to do.
    }
}
