//! ASM's `FieldWriter`: [`FieldWriterState`] holds what ASM's `FieldWriter` holds, and
//! [`FieldWriter`], the field visitor a class writer returns, borrows it with the symbol table.

use crate::attribute::Attribute;
use crate::constant::Constant;
use crate::constants;
use crate::jstr::JavaStr;
use crate::opcodes;
use crate::type_path::TypePath;
use crate::type_reference::TypeReference;
use crate::visitor::{AnnotationVisitor, FieldVisitor};
use crate::writer::annotation_writer::{
    MemberAnnotations, compute_member_annotations_size, put_member_annotations,
};
use crate::writer::attributes::{
    AttributeList, AttributePrototypes, compute_standard_attributes_size, put_standard_attributes,
};
use crate::writer::byte_vector::ByteVector;
use crate::writer::symbol_table::SymbolTable;

/// A `field_info` structure being written (ASM's `FieldWriter` fields).
#[derive(Debug)]
pub(crate) struct FieldWriterState {
    // Note: fields are ordered as in the field_info structure, and those related to attributes
    // are ordered as in Section 4.7 of the JVMS.
    /// The `access_flags` field of the `field_info` JVMS structure. This field can contain ASM
    /// specific access flags, such as `ACC_DEPRECATED`, which are removed when generating the
    /// ClassFile structure.
    access_flags: u32,
    /// The `name_index` field of the `field_info` JVMS structure.
    name_index: i32,
    /// The `descriptor_index` field of the `field_info` JVMS structure.
    descriptor_index: i32,
    /// The `signature_index` field of the Signature attribute of this field, or 0 if there is no
    /// Signature attribute.
    signature_index: i32,
    /// The `constantvalue_index` field of the ConstantValue attribute of this field, or 0 if
    /// there is no ConstantValue attribute.
    constant_value_index: i32,
    /// The runtime (in)visible (type) annotations of this field.
    annotations: MemberAnnotations,
    /// The non standard attributes of this field.
    attributes: AttributeList,
}

impl FieldWriterState {
    /// Constructs a new field writer state (ASM's `FieldWriter` constructor).
    pub(crate) fn new(
        symbol_table: &mut SymbolTable,
        access: u32,
        name: &JavaStr,
        descriptor: &JavaStr,
        signature: Option<&JavaStr>,
        constant_value: Option<&Constant<'_>>,
    ) -> FieldWriterState {
        let name_index = symbol_table.add_constant_utf8(name);
        let descriptor_index = symbol_table.add_constant_utf8(descriptor);
        let signature_index = signature.map_or(0, |s| symbol_table.add_constant_utf8(s));
        let constant_value_index = constant_value.map_or(0, |v| symbol_table.add_constant(v).index);
        FieldWriterState {
            access_flags: access,
            name_index,
            descriptor_index,
            signature_index,
            constant_value_index,
            annotations: MemberAnnotations::default(),
            attributes: AttributeList::default(),
        }
    }

    /// Returns the size of the `field_info` JVMS structure generated by this writer, and adds
    /// the names of its attributes to the constant pool.
    pub(crate) fn compute_field_info_size(&mut self, symbol_table: &mut SymbolTable) -> usize {
        // The access_flags, name_index, descriptor_index and attributes_count fields use 8 bytes.
        let mut size = 8;
        // For ease of reference, we use here the same attribute order as in Section 4.7 of the
        // JVMS.
        if self.constant_value_index != 0 {
            // ConstantValue attributes always use 8 bytes.
            symbol_table.add_constant_utf8(constants::CONSTANT_VALUE);
            size += 8;
        }
        size +=
            compute_standard_attributes_size(symbol_table, self.access_flags, self.signature_index);
        size += compute_member_annotations_size(symbol_table, &self.annotations);
        if !self.attributes.is_empty() {
            size += self.attributes.compute_attributes_size(symbol_table, None);
        }
        size
    }

    /// Puts the content of the `field_info` JVMS structure generated by this writer into the
    /// given byte vector.
    #[allow(clippy::cast_possible_truncation, clippy::cast_possible_wrap)] // Java's ints
    pub(crate) fn put_field_info(
        &mut self,
        symbol_table: &mut SymbolTable,
        output: &mut ByteVector,
    ) {
        let use_synthetic_attribute = symbol_table.major_version() < opcodes::V1_5 as i32;
        // Put the access_flags, name_index and descriptor_index fields.
        let mask = if use_synthetic_attribute {
            opcodes::ACC_SYNTHETIC
        } else {
            0
        };
        output
            .put_short((self.access_flags & !mask) as i32)
            .put_short(self.name_index)
            .put_short(self.descriptor_index);
        // Compute and put the attributes_count field.
        // For ease of reference, we use here the same attribute order as in Section 4.7 of the
        // JVMS.
        let mut attributes_count = 0;
        if self.constant_value_index != 0 {
            attributes_count += 1;
        }
        if self.access_flags & opcodes::ACC_SYNTHETIC != 0 && use_synthetic_attribute {
            attributes_count += 1;
        }
        if self.signature_index != 0 {
            attributes_count += 1;
        }
        if self.access_flags & opcodes::ACC_DEPRECATED != 0 {
            attributes_count += 1;
        }
        attributes_count += self.annotations.attribute_count();
        attributes_count += self.attributes.len();
        output.put_short(attributes_count as i32);
        // Put the field_info attributes.
        // For ease of reference, we use here the same attribute order as in Section 4.7 of the
        // JVMS.
        if self.constant_value_index != 0 {
            let name_index = symbol_table.add_constant_utf8(constants::CONSTANT_VALUE);
            output
                .put_short(name_index)
                .put_int(2)
                .put_short(self.constant_value_index);
        }
        put_standard_attributes(
            symbol_table,
            self.access_flags,
            self.signature_index,
            output,
        );
        put_member_annotations(symbol_table, &self.annotations, output);
        if !self.attributes.is_empty() {
            self.attributes.put_attributes(symbol_table, None, output);
        }
    }

    /// Collects the attributes of this field into the given set of attribute prototypes.
    pub(crate) fn collect_attribute_prototypes(&self, prototypes: &mut AttributePrototypes) {
        self.attributes.collect_attribute_prototypes(prototypes);
    }
}

/// A [`FieldVisitor`] that generates a corresponding `field_info` structure, as defined in the
/// Java Virtual Machine Specification (JVMS).
pub(crate) struct FieldWriter<'a> {
    pub(crate) symbol_table: &'a mut SymbolTable,
    pub(crate) state: &'a mut FieldWriterState,
}

impl FieldVisitor for FieldWriter<'_> {
    fn visit_annotation<'b>(
        &'b mut self,
        descriptor: &JavaStr,
        visible: bool,
    ) -> Option<Box<dyn AnnotationVisitor + 'b>> {
        self.state
            .annotations
            .visit_annotation(self.symbol_table, descriptor, visible)
    }

    fn visit_type_annotation<'b>(
        &'b mut self,
        type_ref: TypeReference,
        type_path: Option<&TypePath>,
        descriptor: &JavaStr,
        visible: bool,
    ) -> Option<Box<dyn AnnotationVisitor + 'b>> {
        self.state.annotations.visit_type_annotation(
            self.symbol_table,
            type_ref,
            type_path,
            descriptor,
            visible,
        )
    }

    fn visit_attribute(&mut self, attribute: &Attribute) {
        // Store the attributes in the <i>reverse</i> order of their visit by this method.
        self.state.attributes.push(attribute);
    }

    fn visit_end(&mut self) {
        // Nothing to do.
    }
}
