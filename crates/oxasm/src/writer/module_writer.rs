//! ASM's `ModuleWriter`: [`ModuleWriterState`] holds what ASM's `ModuleWriter` holds, and
//! [`ModuleWriter`], the module visitor a class writer returns, borrows it with the symbol
//! table.

use crate::constants;
use crate::jstr::JavaStr;
use crate::visitor::ModuleVisitor;
use crate::writer::byte_vector::ByteVector;
use crate::writer::symbol_table::SymbolTable;

/// The Module, ModulePackages and ModuleMainClass attributes being written (ASM's
/// `ModuleWriter` fields).
#[derive(Debug)]
pub(crate) struct ModuleWriterState {
    /// The `module_name_index` field of the JVMS Module attribute.
    module_name_index: i32,
    /// The `module_flags` field of the JVMS Module attribute.
    module_flags: u32,
    /// The `module_version_index` field of the JVMS Module attribute.
    module_version_index: i32,
    /// The `requires_count` field of the JVMS Module attribute.
    requires_count: i32,
    /// The binary content of the `requires` array of the JVMS Module attribute.
    requires: ByteVector,
    /// The `exports_count` field of the JVMS Module attribute.
    exports_count: i32,
    /// The binary content of the `exports` array of the JVMS Module attribute.
    exports: ByteVector,
    /// The `opens_count` field of the JVMS Module attribute.
    opens_count: i32,
    /// The binary content of the `opens` array of the JVMS Module attribute.
    opens: ByteVector,
    /// The `uses_count` field of the JVMS Module attribute.
    uses_count: i32,
    /// The binary content of the `uses_index` array of the JVMS Module attribute.
    uses_index: ByteVector,
    /// The `provides_count` field of the JVMS Module attribute.
    provides_count: i32,
    /// The binary content of the `provides` array of the JVMS Module attribute.
    provides: ByteVector,
    /// The `provides_count` field of the JVMS ModulePackages attribute.
    package_count: i32,
    /// The binary content of the `package_index` array of the JVMS ModulePackages attribute.
    package_index: ByteVector,
    /// The `main_class_index` field of the JVMS ModuleMainClass attribute, or 0.
    main_class_index: i32,
}

#[allow(clippy::cast_possible_truncation, clippy::cast_possible_wrap)] // Java's ints
impl ModuleWriterState {
    /// Constructs a new module writer state (ASM's `ModuleWriter` constructor).
    pub(crate) fn new(name: i32, access: u32, version: i32) -> ModuleWriterState {
        ModuleWriterState {
            module_name_index: name,
            module_flags: access,
            module_version_index: version,
            requires_count: 0,
            requires: ByteVector::new(),
            exports_count: 0,
            exports: ByteVector::new(),
            opens_count: 0,
            opens: ByteVector::new(),
            uses_count: 0,
            uses_index: ByteVector::new(),
            provides_count: 0,
            provides: ByteVector::new(),
            package_count: 0,
            package_index: ByteVector::new(),
            main_class_index: 0,
        }
    }

    /// Returns the number of Module, ModulePackages and ModuleMainClass attributes generated by
    /// this writer.
    pub(crate) fn get_attribute_count(&self) -> usize {
        1 + usize::from(self.package_count > 0) + usize::from(self.main_class_index > 0)
    }

    /// Returns the size of the Module, ModulePackages and ModuleMainClass attributes generated
    /// by this writer, and adds their names to the constant pool.
    pub(crate) fn compute_attributes_size(&self, symbol_table: &mut SymbolTable) -> usize {
        symbol_table.add_constant_utf8(constants::MODULE);
        // 6 attribute header bytes, 6 bytes for name, flags and version, and 5 * 2 bytes for
        // counts.
        let mut size = 22
            + self.requires.size()
            + self.exports.size()
            + self.opens.size()
            + self.uses_index.size()
            + self.provides.size();
        if self.package_count > 0 {
            symbol_table.add_constant_utf8(constants::MODULE_PACKAGES);
            // 6 attribute header bytes, and 2 bytes for package_count.
            size += 8 + self.package_index.size();
        }
        if self.main_class_index > 0 {
            symbol_table.add_constant_utf8(constants::MODULE_MAIN_CLASS);
            // 6 attribute header bytes, and 2 bytes for main_class_index.
            size += 8;
        }
        size
    }

    /// Puts the Module, ModulePackages and ModuleMainClass attributes generated by this writer
    /// in the given byte vector.
    pub(crate) fn put_attributes(&self, symbol_table: &mut SymbolTable, output: &mut ByteVector) {
        // 6 bytes for name, flags and version, and 5 * 2 bytes for counts.
        let module_attribute_length = 16
            + self.requires.size()
            + self.exports.size()
            + self.opens.size()
            + self.uses_index.size()
            + self.provides.size();
        let name_index = symbol_table.add_constant_utf8(constants::MODULE);
        output
            .put_short(name_index)
            .put_int(module_attribute_length as i32)
            .put_short(self.module_name_index)
            .put_short(self.module_flags as i32)
            .put_short(self.module_version_index)
            .put_short(self.requires_count)
            .put_byte_array(self.requires.data())
            .put_short(self.exports_count)
            .put_byte_array(self.exports.data())
            .put_short(self.opens_count)
            .put_byte_array(self.opens.data())
            .put_short(self.uses_count)
            .put_byte_array(self.uses_index.data())
            .put_short(self.provides_count)
            .put_byte_array(self.provides.data());
        if self.package_count > 0 {
            let name_index = symbol_table.add_constant_utf8(constants::MODULE_PACKAGES);
            output
                .put_short(name_index)
                .put_int(2 + self.package_index.size() as i32)
                .put_short(self.package_count)
                .put_byte_array(self.package_index.data());
        }
        if self.main_class_index > 0 {
            let name_index = symbol_table.add_constant_utf8(constants::MODULE_MAIN_CLASS);
            output
                .put_short(name_index)
                .put_int(2)
                .put_short(self.main_class_index);
        }
    }
}

/// A [`ModuleVisitor`] that generates the corresponding Module, ModulePackages and
/// ModuleMainClass attributes, as defined in the Java Virtual Machine Specification (JVMS).
pub(crate) struct ModuleWriter<'a> {
    pub(crate) symbol_table: &'a mut SymbolTable,
    pub(crate) state: &'a mut ModuleWriterState,
}

#[allow(clippy::cast_possible_truncation, clippy::cast_possible_wrap)] // Java's ints
impl ModuleVisitor for ModuleWriter<'_> {
    fn visit_main_class(&mut self, main_class: &JavaStr) {
        self.state.main_class_index = self.symbol_table.add_constant_class(main_class).index;
    }

    fn visit_package(&mut self, packaze: &JavaStr) {
        let index = self.symbol_table.add_constant_package(packaze).index;
        self.state.package_index.put_short(index);
        self.state.package_count += 1;
    }

    fn visit_require(&mut self, module: &JavaStr, access: u32, version: Option<&JavaStr>) {
        let module_index = self.symbol_table.add_constant_module(module).index;
        let version_index = version.map_or(0, |v| self.symbol_table.add_constant_utf8(v));
        self.state
            .requires
            .put_short(module_index)
            .put_short(access as i32)
            .put_short(version_index);
        self.state.requires_count += 1;
    }

    fn visit_export(&mut self, packaze: &JavaStr, access: u32, modules: &[&JavaStr]) {
        let package_index = self.symbol_table.add_constant_package(packaze).index;
        self.state
            .exports
            .put_short(package_index)
            .put_short(access as i32);
        self.state.exports.put_short(modules.len() as i32);
        for module in modules {
            let module_index = self.symbol_table.add_constant_module(module).index;
            self.state.exports.put_short(module_index);
        }
        self.state.exports_count += 1;
    }

    fn visit_open(&mut self, packaze: &JavaStr, access: u32, modules: &[&JavaStr]) {
        let package_index = self.symbol_table.add_constant_package(packaze).index;
        self.state
            .opens
            .put_short(package_index)
            .put_short(access as i32);
        self.state.opens.put_short(modules.len() as i32);
        for module in modules {
            let module_index = self.symbol_table.add_constant_module(module).index;
            self.state.opens.put_short(module_index);
        }
        self.state.opens_count += 1;
    }

    fn visit_use(&mut self, service: &JavaStr) {
        let index = self.symbol_table.add_constant_class(service).index;
        self.state.uses_index.put_short(index);
        self.state.uses_count += 1;
    }

    fn visit_provide(&mut self, service: &JavaStr, providers: &[&JavaStr]) {
        let service_index = self.symbol_table.add_constant_class(service).index;
        self.state.provides.put_short(service_index);
        self.state.provides.put_short(providers.len() as i32);
        for provider in providers {
            let provider_index = self.symbol_table.add_constant_class(provider).index;
            self.state.provides.put_short(provider_index);
        }
        self.state.provides_count += 1;
    }

    fn visit_end(&mut self) {
        // Nothing to do.
    }
}
